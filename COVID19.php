            <p> <h2 id="prevention">COVID-19 Prevention while working at UWPR</h2></p>
			<a href="#page">Back to Top</a>
				<br><br>
			
			
			<p><strong>Review theUniversity of Washington Guidelines for COVID-19 prevention while working in the laboratory</strong>
            <br><a target="new" href="https://www.ehs.washington.edu/covid-19-health-and-safety-resources">COVID-19 Health and Safety Resources</a>
			<br><a target="new" href="https://www.washington.edu/research/announcements/mitigating-impacts-to-research-activities-due-to-covid-19/">Mitigating Impacts to Research Activities Due to COVID-19</a>
			<br><a target="new" href="https://www.washington.edu/research/announcements/message-from-vice-provost-for-research-mary-lidstrom-governor-updates-allowable-areas-of-research/">Allowable areas of research</a>
			<br><a target="new" href="https://www.washington.edu/coronavirus/#health">COVID-19: facts and resources</a>
			</p>
			
			<p><strong>7/8/2021 In-Person Work COVID-19 Prevention Plan</strong>
			
			<br>Effective 7/8/21, in-person work is permitted for all personnel. You must be fully vaccinated to work in-person without a face covering. 
			Face coverings are optional for fully vaccinated individuals at UW campuses with specific exceptions that include health-care and child-care facilities, and UW shuttles. 
			You must continue to wear face coverings in these settings, regardless of your vaccination status 
			<br>Required: Individuals must verify that they have been fully vaccinated, or declare a medical, religious or philosophical exemption.
			<br><a target="new" href="https://www.washington.edu/coronavirus/vaccination-requirement/">UW COVID-19 vaccination requirement</a>
			<br><br><strong>Physical distancing and capacity: </strong>
			<br>Consistent with UW, UWPR is lifting indoor distancing and COVID-19 capacity requirements, though distancing is still recommended for unvaccinated individuals.
			<br>Visitor logs for in-person scheduling are no longer required.
			<br>
			<br>All individuals are still required to monitor symptoms daily, stay home if they are sick or experiencing COVID-19 symptoms, 
			and report to EH&amp;S if they test positive for COVID-19 or have had close contact with someone who tested positive, regardless of their vaccination status. Report through email at covidehc@uw.edu or call 206-616-3344.
			</p>

			
			
			
			
			
			<p> <strong>4/13/2020 UWPR lab specific COVID-19 guidlines <a target="new" href="/docs/safety/COVID19_UWPR_Specific_Guidelines.pdf">(pdf)</a></strong></p>
			<ul>
			<li>All users must abide by the guidelines outlined in the long-form guidelines for COVID-19 prevention</li>
			<li><a target="new" href="https://www.ehs.washington.edu/training/covid-19-safety-training-back-workplace">COVID-19 Safety Training: Back to the Workplace</a> 
			must be completed by all University personnel before or upon returning to work on site at a University location</li>
			<br>
			<li>Social Distancing: stay 6ft apart at all times </li>
			<li>Follow UW's <a target="new" href="https://www.ehs.washington.edu/system/files/resources/facemask-guidance-COVID-19.pdf">Guidance on Facemask use for preventing the spread of COVID-19</a></li>
			<li>No more than three people should be working in the UWPR portion of the lab at any given time</li>
			<li>Review the <a target="new" href="/docs/safety/COVID19_B59_Floorplan_2020.pdf">COVID19_B59_Floorplan_2020</a> before working in the lab</li>
			<br>
			<li>Enter the lab through the double doors on the south side of the lab (by the sink)</li>
			<li>Wash hands when entering and before leaving the lab</li>
			<li><strong>COVID-19 prevention training, contact tracing and self attestation:</strong>
			<br>Sign the COVID-19 form to confirm that you read the COVID-19 prevention guidelines and that you don't have symptoms. 
			     Do not enter or work the lab if you experience any symptoms
			<br>Sign that form every day when you physically work in the lab for contact tracing</li>
			<li>Use appropriate PPE including gloves, eye protection and lab coats</li>
			<br>
			<li>Only touch surfaces related to the instrument you are using</li>
			<li>Keyboard, mouse, table and chair will be wiped before and after your instrument time</li>
			<br>
			<li>All fittings to connect columns are sonicated in 100% Methanol for 10 min prior to your start time</li>
			<li>Put all used/touched fittings in the beaker labeled “used fittings” for sanitation</li>
			<br>
			<li>Key cards and lanyards are sanitized prior to your start time</li>
			<li>After you are finished leave the key card on the computer desk by the instrument you used</li>
			<br>
			<li>Users must decontaminate all common surfaces (blue shaded area on floor plan) and instruments before and after use</li>
			<li>Date and initial the log when using and decontaminating surfaces and instruments </li>
			<li>Common instruments include microscopes, pressure cells and/or laser puller, centrifuges, pipettes </li>
			<li>This also applies if you use the office space, max occupancy is one person in the office  </li>
			<li>Methanol and Kim wipes to clean surfaces are available throughout the lab </li>
			<br>
			<li>Do not enter Bruce lab space, green shaded area on floor plan</li>
			<br><br>
			

			</ul>
			
			
