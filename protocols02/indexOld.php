				<p><strong>Cell Fractionation (organellar proteomics)</strong>
				<br>When fractionating proteins based on their cellular localization all possible precautions should be taken to isolate the desired organelle. 
				Contaminating proteins from other cytosol or other organelles should be expected. 
				Repeated analyses with strong statistical tests are often needed to differentiate contaminating proteins from true organellar proteins. 
				Another (undesired) organelle can serve as a good negative control.
