				<p><strong>Protein separation 1D and 2D Gel</strong>
				<br>Sodium dodecyl sulfate polyacrylamide gel electrophoresis (SDS-PAGE) is a very common method for separating proteins based on their molecular weight. 
				Protein separation by SDS-PAGE can be used to estimate relative molecular mass, to determine the relative abundance of major proteins in a sample, 
				and to determine the distribution of proteins among fractions. SDS-PAGE can also be used as a tool to assess purity of protein samples and 
				to monitor the progress of a fractionation or purification procedure. 
				Two-dimensional (2D) electrophoresis separated proteins first by their isoelectric point and then by their molecular weight.
				<br>Different staining methods can be used like Coomassie Blue ( range) and Silver stain (range) to visualize the protein bands. 
				Techniques such as Western blotting are used to detect specific proteins or protein modification.
				<br> To identify proteins by LC-MS, proteins can be digested in the gel or on the membrane (western blot) and peptides can be extracted for analysis.
			    </p>
				
