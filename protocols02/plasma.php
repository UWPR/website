			<p><h2 id="plasmavsserum">Plasma vs Serum</h2>
				<br>
					<br>Blood from a single donation or sample can be separated into different components: proteins, red blood cells, white blood cells, clotting factors, etc., and used for their individual purposes. 
					Similarly, plasma and serum are obtained from the blood by centrifugation.
					<br>Plasma is produced when whole blood is collected in tubes that are treated with an anticoagulant. The blood does not clot in the plasma tube. 
					The cells are removed by centrifugation and the supernatant is designated plasma.  
					<br>Serum is the liquid fraction of whole blood that is collected after the blood is allowed to clot. The clot is removed by centrifugation and the resulting supernatant is
					designated serum.
						
				
				<p><h2 id="immunodepletion">Immunodepletion</h2>
				<br>
				<br>The wide dynamic range of protein concentrations present in serum and plasma represents a major challenge for the analysis of the proteome. 
				The range of plasma protein concentrations, from low abundance proteins such as cytokines (pg/mL) to albumin (30-45 mg/mL), represents at least 
				10 orders of magnitude. Analysis of low abundance proteins by even the most sensitive of methods for proteomics greatly benefits from the removal 
				of high abundance proteins that may interfere with their detection.
				Plasma Immunodepletion strategies specifically remove the most abundant proteins from human plasma or serum in preparation for further proteomics analysis,
				enabling deeper penetration into the plasma proteome, here are a couple of examples:
