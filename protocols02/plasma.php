			<br><b>Immunodepletion of High Abundance Serum Proteins (from Ref 4)</b>
<br>
			<br>Materials
			<ol>
			<li>Bradford microtiter plate assay (Pierce) and plate reader.
			<li>Bovine serum albumin (BSA) standards.
			<li>Proteome Purify 12 Immunodepletion Resin (R&amp;D Systems).
				A 50 % slurry of a proprietary absorption gel in Phosphate
				Buffered Saline (PBS) with 0.02 % sodium azide (pH 7.4).
			<li>Spin-X Filter Units (Corning Costar). Centrifuge tube filters
				with a 0.22 &#956;m pore cellulose acetate membrane.
			<li>5,000 Da MWCO filters (Sigma).
			<li>Rotary shaker or mixer.
			<li>Vortex.
			<li>Centrifuge.
			
			</ol>
			
			<br>Method
			<ol>
			<li>Determine protein concentration using the Bradford microtiter plate assay. Make a 5 mg/mL stock of BSA in HPLC grade water and prepare serial dilutions 
			of 0, 0.25, 0.5, 1.0, 2.5, and 5.0 mg/mL to make a standard curve. Use a 96-well flat bottomed assay plate and make triplicate measurements for the BSA standards 
			and four replicates for the experimental samples. For this, add 2 &#956;L of sample per well and 200 &#956;L of assay reagent and mix without introducing bubbles. Use a 
			plate reader at a wavelength of 595 nm and calculate protein concentrations using the standard curve (It is recommended that at least three replicate assays are 
			performed for each sample for accurate protein determination).
			<li>For each PC time group, add 30 &#956;L of serum to a test tube.
			<li>Add 3.0 mL of the suspended Immunodepletion Resin to each serum sample ( It is essential that the Immunodepletion Resin be a homogeneous suspension prior to pipetting).
			<li>Incubate on a rotary shaker with end-over-end mixing for 30 min. The mixing speed should be adequate to keep the Immunodepletion Resin in suspension.
			<li>After the incubation period, pipette equal volumes of the Immunodepletion Resin slurry into the upper chamber of six Spin-X Filter Units.
			<li>Centrifuge for 2 min at 2,000 x g and collect immunodepleted serum in a microcentrifuge tube. The combined volume of the depleted serum filtrates will be approximately 1,000-1,500 &#956;L.
			<li>Dispose of the used Immunodepletion Resin (The Spin-X Filter Units may be cleaned with deionized water followed by 20 % ethanol and saved for reuse).
			<li>Aliquot equal volumes of each immunodepleted serum sample into 3 x 5 kDa MWCO filtration devices. Concentrate each by centrifugation at 13,000 x g for 20 min.
			<li>Combine concentrated triplicate samples of the same PC time group. The volume of the combined filtrates should be approximately 150 &#956;l.
			<li>Determine protein concentration of each immunodepleted serum sample using the Bradford microtiter plate assay, as described in step 1 above (Depletion of the serum or plasma will 
			result in the removal of greater than 90 % of the twelve most abundant proteins. If higher levels of depletion are required, the sample should be concentrated (5,000 Da MWCO spin concentrator) 
			and depleted a second time. The depleted sample will be in a buffer of PBS with 0.02 % sodium azide. Spin concentrators are recommended if desalting is required).
</ol>
			
			<br><h2 id="lectin">Lectin Affinity Chromatography (from Ref 4)</h2>
				<br>
			<br>
			<br>The most common application of lectin affinity chromatography is to separate glycoproteins from non-glycosylated proteins, or one glycoform from another glycoform.
			<br>
			<br>Materials
			<ol>
			<li>Concanavalin A (ConA) lectin resin (Thermo Fisher Scientific); 1.1 mL of settled resin supplied as a 50 % slurry.
			<li>Wheat Germ Agglutinin (WGA) lectin resin (Thermo Fisher Scientific); 1.1 mL of settled resin supplied as a 50 % slurry.
			<li>Jacalin lectin resin (Vector Laboratories); 2.0 mL of settled resin supplied as a 50 % slurry.
			<li>Glycoprotein Isolation Kit Binding/Wash Buffer (Thermo Fisher Scientific). A total volume of 6.5 mL of a 5x stock solution.
			<li>Elution Buffer; 2 % formic acid in HPLC grade water.
			<li>Column Accessory Pack (Thermo Fisher Scientific). Spin columns (10x) with bottom caps and collection tubes (20x).
			<li>Rotary shaker or mixer.
			<li>Vortex.
			<li>Centrifuge.
			</ol>
			
			<br>Method
			<ol>
			<li>Equilibrate all buffers to room temperature.
			<li>Dilute immunodepleted serum samples 4:1 with 5x Binding/Wash Buffer stock solution. The total volume after dilution must not exceed 800 &#956;L.
			<li>From the 5x stock solution, prepare 1x Binding/Wash Buffer with HPLC grade water.
			<li>Gently swirl the bottle of ConA lectin resin to obtain a homogeneous suspension. Use a wide-bore or cut pipette tip to transfer 100 &#956;L of 50 % resin slurry to a 1 mL Eppendorf tube.
			<li>Repeat step 4 for WGA and Jacalin lectin resins, adding all three resins to the same Eppendorf tube. Gently vortex the multi-lectin resin mixture to obtain a homogeneous suspension.
			<li>Insert a column into a collection tube. Pipette 200 &#956;L of the multi-lectin resin solution into this. 
			<li>Centrifuge for 1 min at 1,000 x g and discard the storage buffer. Reuse the collection tube through to step 18 .
			<li>Place column in collection tube. Wash the multi-lectin resin solution with 200 &#956;L of the 1x Binding/Wash Buffer by centrifugation for 1 min at 1,000 x g . Discard the fl ow-through. Repeat this step two times.
			<li>Place bottom cap on column and add immunodepleted serum sample to the resin. Close the top cap.
			<li>Incubate for 10 min at room temperature with end-over-end mixing.
			<li>Remove top cap and then bottom cap from column. Place column in the collection tube and replace top ( see Note 7 ).
			<li>Centrifuge for 1 min at 1,000 x g . Collect the fl ow-through containing unbound/non-glycosylated proteins. Store on ice.
			<li>Reinsert column and add 400 &#956;L 1x Binding/Wash Buffer to the resin. Cap column and centrifuge for 1 min at 1,000 x g . Collect the fl ow-through and combine with that of step 12. Repeat this step.
			<li>Place bottom cap on column and add 400 &#956;L 1x Binding/Wash Buffer to the resin. Cap column and incubate for 5 min at room temperature with end-over-end mixing.
			<li>Remove top cap and then bottom cap from column. Place column in the collection tube, and replace top cap. Centrifuge column for 1 min at 1,000 x g . Discard the flow-through. 			
			<li>Repeat steps 14 and 15 .
			<li>Replace bottom cap on column. Add 200 &#956;L Elution Buffer to resin and cap column. Incubate column for 5 min at room temperature with end-over-end mixing.
			<li>Remove top cap and then bottom cap from column. Place column in a new collection tube. Replace top cap and centrifuge column for 1 min at 1,000 x g .
			<li>Carefully set aside the collection tube and remove top cap.
			<li>Repeat steps 17 - 19 . Collect eluate in the same collection tube containing eluate from the fi rst elution. Store eluted glycoprotein fraction on ice for immediate use or freeze for later analysis.
			<li>Determine protein concentration of both glycoprotein and non-glycoprotein fractions using the Bradford microtiter plate assay, step 1 above.
			</ol>
         
		 <br><h2 id="trypsin">Trypsin Digestion and TMT Labeling (from Ref 4)</h2>
				<br>
		 <br>
		 <br>Isobaric labeling with stable isotopes is one of the preferred quantification strategies. Now with the addition of the TMT 10-plex, up to ten samples can be analyzed in a single run, saving you instrument time/money. 
		 <br>Reagents and protocol are provided in the TMTsixplex Isobaric Mass Tagging Kit. Carry out all steps from this point forward using low retention Eppendorf tubes.
		 <br>
			<br>Materials
			<br>
			<ol>
			<li>Low retention Eppendorf tubes.
			<li>Dissolution buffer: 100 mM triethyl ammonium bicarbonate (TEAB) (pH 8.0), 0.5 % (w/v) SDS. Aliquot and store at -20 <sup>o</sup>C.
			<li>Reducing solution: 200 mM tris(2-carboxyethyl) phosphine in 200 mM triethyl ammonium bicarbonate (pH 8.0). Prepare fresh.
			<li>Alkylation solution: 375 mM iodoacetamide in 100 mM TEAB (pH 8.0). Prepare fresh.
			<li>Trypsin solution: 500 ng/&#956;L sequencing-grade modified trypsin (Promega) in 5 mM acetic acid. Store at -20 <sup>o</sup>C.
			<li>SpeedVac.
			<li>Acetonitrile (ACN): 100 % HPLC grade.
			<li>TMTsixplex Isobaric Mass Tagging Kit (Thermo Fisher Scientific).
			<li>Quenching solution: 5 % hydroxylamine in 200 mM TEAB (pH 8.0).
			</ol>
			
			<br>Method
			<ol>
			<li>Dry down 100 &#956;g of protein from each of the fractions in a SpeedVac and resuspend the protein pellets in 100 &#956;L of dissolution buffer (100 mM TEAB) (pH 8.0), 0.5 % (w/v) SDS.
			<li>Add 5 &#956;L of reducing solution (9.5 mM final concentration of tris(2-carboxyethyl) phosphine) and incubate for 1 h at 55 <sup>o</sup>C.
			<li>Add 5 &#956;L of freshly prepared alkylation solution (17 mM final concentration of iodoacetamide) and incubate for 30 min at room temperature in the dark.
			<li>Add 5 &#956;L of trypsin solution (2.5 &#956;g/100 &#956;g protein) and incubate overnight at 37 <sup>o</sup>C.
			<li>Reconstitute a tube of each TMT label in 41 &#956;L of 100 % ACN and carefully add to the appropriate sample tube.
			<li>Allow labeling reactions to proceed for 1 h at room temperature.
			<li>Quench reactions by adding 8 &#956;L of quenching solution and incubate for 15 min at room temperature.
			<li>Combine samples at equal amounts and dry down in a SpeedVac.
			</ol>
			
			<br>Either proceed to a C18 cleanup step to remove excess TMT and SDS or some peptide separation protocol like SCX or high pH reversed phase chromatography, to separate the peptides in addition to the cleanup.
			
