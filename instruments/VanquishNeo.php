<h2 id="specifications">System specifications</h2>
<a href="#top">Back to Top</a>
	<br>
	<br>
	<ul><strong>System pressure</strong>
		<li>up to 1500 bar (21,750 psi)</li>
	</ul>
	<ul><strong>Flow range</strong>
		<li>1 nL/min – 100 μL/min, in 1 nL increments</li>
		<li>100 nL/min – 100 μL/min, recommended</li>
	</ul>
	<ul><strong>Injection volume range</strong>
		<li>0.01–25 μL</li>
	</ul>
	<ul><strong>Injection volume precision</strong>
		<li>From 0.05 to 0.20 µL: ≤5.0% RSD</li>
		<li>From 0.20 to 0.50 µL: ≤1.5% RSD</li>
		<li>From 0.50 to 2.00 µL: ≤0.5% RSD</li>
		<li>Above 2 µL: ≤0.25% RSD </li>
	</ul>
	
