<p>The TSQ Vantage, a triple quadrupole mass spectrometer, includes a Qualitative Enhanced Data scanning function (QED).  This proprietary scan function allows the instrument to make data-dependent decisions in response to the sample signals and produce qualitative information in addition to the precise and sensitive quantitative information. The specificity provided by H-SRM followed by QED MS/MS provides uncompromised quantitation performance at low levels followed by a fast, highly-specific full MS/MS scan for confirmation.  The patented G2 ion optics (S-lens) provides better transfer (less loss) of more ions to the detector giving better sensitivity, bigger peaks, and better reproducibility in the low end. Additionally, the standard hyperbolic (HyperQuad™ ) quadrupole mass filters reduce chemical noise (H-SRM).</p>

