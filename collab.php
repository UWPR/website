<p>The UWPR is offering analytical and instructional expertise in state of the art mass spectrometric techniques and data analysis with the 
	  primary aim of providing UW investigators with "hands-on" training and access to contemporary resources needed to develop and meet their proteomics research interests.

	  <p>Access to UWPR resources is through collaborations with <a target="new" href="/contact.php">Resource members or affiliated research labs</a>.
	  We strongly recommend that you discuss your proteomics project and the sample preparation with Resource members 
	  prior to preparing samples! Check out the sample preparation guidelines on our <a target="new" href="methods.php">Methods page</a>.
      
	  <p>In order to use the resources, you will have to undergo the appropriate training and follow all the usage <a target="new" href="/docs/UWPR_Guidelines_selfServ.pdf">guidelines (pdf)</a>. 
		The level of instruction is such that following completion of the initial training (usually 4 to 6 hrs) and several periods of supervised use, the researcher may exercise independent, 
		unattended use of an instrument with instructor approval. The training is instrument specific and is provided during the signed up instrument time and has to be coordinated with UWPR staff. 

      <p>The UWPR is operated as a Cost Center through which institutional users contribute to the upkeep of the resource by means of a recharge system. 
	  Rates are based on the operating costs and individual instrument usage. To keep the operating costs low, our collaborators must supply all the consumables 
	  needed for sample preparation and mass spec analysis (including LC columns, vials etc, as per usage guidelines). 

      <p>All rates are reviewed and approved by the University of Washington Administration and are subject to change without notice. 
	  To view the current fee schedule, register and log into to the Internal Proteomics Resource website using the login form above.

      <p><h2 id="access">Access to UWPR resources and services</h2>
	  <a href="#page">Back to Top</a>
				<br><br>
	  
	  <p>To initiate a new collaboration, register and log in using the login form above. On the Welcome page click on the link "Start new collaboration" and submit a detailed project description.  
	  <br>Note UW employees using UW worktag (budget numbers) for billing can choose between self service (do the LC-MS analyses yourself) or full LC-MS service (i.e. LC-MS analyses done by UWPR personnel). 
	  When submitting your project description make sure to check "Mass spec analysis by UWPR personnel" NO for self service and YES for full LC-MS service (note additional labor rates apply).
	  
	  
	  <div style="background-image: url('/images/collab_03.png'); height: 796px; width: 878px;"></div>
	  
	  <br><br><p><h2 id="selfservice">Self Service:</h2>
	  <a href="#page">Back to Top</a>
				<br>
	  
	  <br><br>Download the <a target="new" href="/docs/UWPR_Guidelines_selfServ.pdf">Self service guidelines (pdf)</a>.
	  
	  <ul>
	  
	  <li>After submitting the project details and billing information, you'll have to request sign up privileges via email. Once we grant you access you will be able to schedule instrument time up to max 20 days (480hrs). 
	  <br><br><li><strong>Do NOT block instrument time unnecessarily! Your self sign up rights can and will be revoked. </strong>
	  <br><br>
	  <li>There is a non-refundable fee for signing up. The fee is a percentage of the total cost and will be billed even if you cancel your instrument time. 
	  <li>For each consecutive time span one single setup fee will be charged.
	  <li>There is a 48 hrs cancellation time, i.e. you can cancel instrument time up to 48hr before the start time, after that the system will no longer allow you to make changes. 
	  So it's very simple: you will be charged for all the sign up fees and the instrument time you cannot cancel yourself.
	  <li>Make sure to coordinate with UWPR personnel to get access to the facility and schedule instruction time if training is needed. 
	  <li><strong>Start and end times are strictly enforced.</strong> If you start early or don't finish, clean up and return the key card on time you will be charged extra time at the hourly rate (always rounding up to the next full hour). 
	  <li> Instrument start times are 10 am and 2 pm (Note UWPR personnel may need time to prep the instrument at the beginning of your start time)
	  <li> Instrument end times are 10 am, 2 pm and 6 pm.
	  <li>If you finish early and clean up/return the key card before the next time block starts, unused instrument time will be backed out to the end of the last acquisition (always rounding up to the next full hour), 
	  but no more than back to the end of the previous time block. The sign-up fee will not be backed out: 
	  <ul>
	  <li>e.g. if you are signed up until 10 am, time from the end of your last acquisition (always rounding up to the next full hour) will be backed out, maximum back to 6 pm the day before.
	  <li>if you are signed up until 6pm, time will be backed out to max 2 pm that same day
	  <li>if you are signed up until 2pm, time will be backed out to max 10 am that same day
	  <li>So for example, if you wish to sign up for the whole weekend (e.g. until Mon 10am), so you don't have to cleanup during the weekend, and your last run finishes e.g. Saturday morning, you will be charged until Sunday 6pm.
	  </ul>
	  <li>If you can't make it in to clean up and ask UWPR personnel to clean up for you, you will be charged the full time block (no time will be backed out).
	  <li>If you sign up into the weekend, be prepared to come in and clean up your stuff during the weekend, in case someone signs up to use the instrument.
	  <li>You will have to provide your own consumables (columns and autosampler vials), 
	  <br>click here to download a list of <b><a href="/docs/protocols05/LC_MS_Consumables.xls"> LC-MS commonly used consumables (xls)</a></b>
	  <li>UWPR personnel can help you with your data analysis needs as well, please contact us to discuss details.
	  </ul>
	  
	  
	  <p><h2 id="fullservice">Full LC-MS Service:</h2>
	  <a href="#page">Back to Top</a>
				<br><br>
	  <br>For small projects with limited number of samples we offer full LC-MS service (<a target="new" href="/docs/UWPR_Guidelines_fullServ.pdf">guidelines (pdf)</a>). You will still have to process the samples, but UWPR personnel will do the LC-MS analysis and help you with data analysis.  
	  Feel free to contact us if you need help with project design/sample prep procedures. Note all the samples have to be processed and be "mass spec ready", i.e. you will do all the sample preparations. 
	  To start the collaboration submit the project details and billing information online. 
	  When you have your samples ready for LC-MS analysis, submit the <b><a href="/pr/costcenter_resources/UWPR sample submission form.xlsx">Sample Submission Form (xlsx)</a></b> and coordinate with UWPR personnel to drop off your "mass spec" ready samples. 
	  Note we use the  <a href="/pr/costcenter_resources/UWPR sample submission form.xlsx">Sample Submission Form (xlsx)</a> to track experimental details for future reference. 
	  Once we receive both the samples and the submission form, UWPR personnel will schedule the necessary instrument time to analyze your samples. There is a non-refundable fee for signing up. 
	  The fee is a percentage of the total cost and will be billed even if you cancel your instrument time. The cutoff for instrument time cancellation is 48 hrs prior to the start time. 
	  <br>UWPR personnel can help you with your data analysis needs as well. 

	  
	  
	  <p><h2 id="billing">Billing</h2>
	  <a href="#page">Back to Top</a>
				<br><br>
				<br>The cost is based on the setup fee, the sign up fee and the instrument time cost you signed up for and will be invoiced the first business day the month following the signed up time. 
				<br>The sign-up fee can NOT be canceled. Instrument time cancellation is 48hr prior to the start time of the time block you wish to cancel. Any time that is not cancelled will be charged. 
	  
				<br>For full LC-MS service the cost is based on the time it take to analyze your samples plus a minimum of 2hrs to prepare the column and run quality control samples. 
				The <a href="/pr/costcenter_resources/UWPR sample submission form.xlsx">Sample Submission Form (xlsx)</a> can help estimate the time needed to analyze your samples. 
					<br>The current rates can be downloaded from the "Welcome page" when you login. The billing cycle is monthly.
	             
       

