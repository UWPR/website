            <h2>Protein Separation and Enrichment</h2>
                              
                           
                           
					<p>The most challenging proteomics studies are those that try to identify and quantify global proteomes. Many experiments require a reduction of protein complexity by separating the proteins. 
					<br>One approach is to focus on the subproteome of an organelle using classical subcellular fractionation techniques.
					<br>Alternatively, sample complexity can also be effectively reduced using enrichment techniques like immunoprecipitations or activity- or affinity-based approaches. 
					<br>Enrichment can also be directed toward a specific characteristic of proteins for example toward glycoproteins [Ref 2], phoshoproteins or newly synthesized proteins [Ref 3]. 
					<br>Proteins can also be separated by gels (SDS-PAGE), chromatography (FPLC and HPLC) or Gel-Free separations. 
						
