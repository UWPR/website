                              <h1>Protein Preparation and Separation</h1>
                              <span class="byline">Protein extraction, modification and separation protocols </span>
                           </header>
						   
						   <p>Protein extraction is an important step in any proteomics experiment. It
                often starts with cell lysis and cell fractionation, followed by specific
                enrichment and/or isolation of a particular protein of interest (affinity
                purification), or removal of interfering or contaminating substances (i.e. immunodepletion).

                <p>Many techniques are available for the disruption of cells, including
                physical and detergent-based methods. Historically, physical lysis has been
                the method of choice for cell disruption; however, physical methods often
                require expensive equipment (french prss, homogenizer, cryogrinding).
                <br>Detergent-based lysis is more popular due to ease of use, low cost and
                efficient protocols. However, many detergents interfere with the downstream LC-MS analysis. 
				A list of MS compatible detergents can be found on our protein digestion page.

