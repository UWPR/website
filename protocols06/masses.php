                masses are based on the sum of the elemental masses where the elemental masses
                are from <a href="http://www.unimod.org/masses.html">Unimod</a>.
                You can also download <a href="/docs/amino_acid_masses.xlsx">this spreadsheet</a>
                where the average and monoisotopic masses for each amino acid are calculated
                within the spreadsheet from the listed elemental values (that you can
                change).
