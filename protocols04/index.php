                        <p><h2 id="scx">Strong cation-exchange (SCX) chromatography </h2>
				<br>
				<br>SCX has been used extensively for the fractionation of proteins and peptides based on charge. 
				The SCX stationary phase usually contains aliphatic sulfonic acid groups that are negatively charged in aqueous solution, therefore tightly binding 
				any strongly basic analytes. To recover the analyte, the resin is then washed with a solvent neutralizing this ionic interaction. Most tryptic 
				peptides in acidic pH are characterized by a net charge of +2 and above, and they can be therefore separated by SCX from peptides possessing a net 
				charge of +1, such as trypsin-generated phosphopeptides, C-terminal peptides, or peptides with blocked N-termini (i.e., peptides with blocked N-terminal 
				free amine group, for instance, by N-acetylation), as well as from peptides containing higher charges, including ones containing missed cleavages and 
				therefore more arginine and lysine residues.
				SCX fractionation can also be performed in a solid-phase extraction cartridge format for a rapid but lower resolution fractionation.
				SCX can also be conducted in microscale solid-phase extraction format (i.e. after IMAC) by utilizing a stage tip packed with an SCX disk.
				<br>
				<ul>
				<li>Fractionation of peptides by strong cation-exchange liquid chromatography.
				Chan KC, Issaq HJ. <i>Methods Mol Biol.</i>  2013;1002:311-5.
