                <P>Pressure cells are designed to pack/load microbore capillaries, such as polyimide coated fused silica. They can be used to pack columns and pre-columns (traps) with a slurry of beads or to load samples onto packed traps or columns.  We routinely use 360 &#181;m OD capillaries with  50-150 &#181;m ID's to pack columns and traps with 3-5 &#181;m beads of various chemistries (C18, SCX). 

