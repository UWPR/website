                <P>The UWPR nanospray source was first designed in 2007 to be used on ThermoFisher instruments (LTQ, LTQ-OrbitrapXL and TSQ)
				over the years the flexible design was modified and today fits all the Thermo instruments (including QExactive series and the new source design on the Tribrid series instruments as well as the TSQ Altis). 
				
				
				
				<P>The UWPR NSI source offers all the benefits and features of commercial NSI sources:
				<P>
				<P>
                   <ul>
                   <li>Lower flow rates: no drying gas or thermal heating is required and increased sensitivity compared to higher flow ESI
                   <li>Higher tolerance to a wide variety of liquid compositions than conventional ESI
                   </ul>

                   

                <P>But in addition this NSI source offers significant improvements over most commercial sources:
                   <ul>
                   <li>Great flexibility: it accommodates columns of all length, in house packed or commercial columns, as well as configurations with traps, spray tips etc.
                   <li>The source can be customized to your specific needs: e.g. mounting of cameras, LED lights or anything else you can think of
                   <li>Additionally this NSI source can be used in conjunction with the Thermo NSI probes (static , dynamic and packed tip probe)
                   <li>The open design allows for leaks to be detected immediately
                   <li>Significantly lower cost, you can download parts list and instruction how to assemble it for free, allowing you to build the NSI source at a fraction of the cost of commercial sources
                   <li>All the parts are commercially available
                   </ul>
				
