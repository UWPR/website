			<p>PPS Silent surfactant is no longer available from Agilent or Abcam (former Expedion), but CreativeProteomics MSPro is selling a variety of acid cleavable surfactants:
			<br><a target="new" href="https://mspro.creative-proteomics.com/ms-protein-sample-preparation-list-108.htm">MS Protein Sample Preparation products</a>
			<br>
			<br>Use the PPS Silent Surfactant (acid-cleavable detergent) from 
				     <a href="/docs/protocols03/expedeon_PPS_SilentSurfactant.pdf">Expedeon</a> (former ProteinDiscovery) or 
				     <a href="/docs/protocols03/Agilent_PPS_SilentSurfactant.pdf">Agilent</a> to extract and solubilize hydrophobic proteins  and improve in-solution enzymatic digestions of proteins.
			
		    <br><br>PPS is an effective detergent designed to have minimal negative impact on mass spectrometry. Simply lowering the pH of the digest buffer cleaves this reagent, allowing LC-MS analysis.

			<p><b>Materials</b>
			<br>All solvents should be HPLC grade, NEVER use pipette tips when transferring acids &gt;2% in concentration!
			<br><a target="new" href="/docs/protocols05/Avoid Contaminations.pdf">Avoid Contaminations (pdf)</a></li>
			<ol>
			<li>PPS Silent Surfactant (Expedeon Part # 21011, 1 mg vial; Part # 21010, 10 mg vial or Agilent Part # 400500, 1 mg vials; Part # 400501, 10 mg vial)
			<li>50 mM Ammonium bicarbonate (Fisher, part # A643-500) in H<sub>2</sub>O (79.1g/mol): 3.955g/100ml)(pH 7.8) make fresh
			<li>500 mM Dithiothreitol DTT (Fisher, part # PI-20291) in H<sub>2</sub>O
			<li>500 mM Iodoacetamide IAA (Fisher, part # AC12227-0050) in H<sub>2</sub>O (0.0185g/ml; always prepare fresh, light sensitive)
			<li>100 mM CaCl<sub>2</sub>
			<li>500mM HCl
			<li>250 ng / &#956;g/&#956;L Trypsin in 0.01% acetic acid (modified, sequencing grade, Promega, part # V5111, 5 x 20&#956;g/&#956;g)
			<li>Water (Fisher, part # W6-4 optima LCMS grade)
			<li>Eppendorf LoBind Microcentrifuge Tubes: Protein (Fisher, part # 13-698-794)
			</ol>
			
			<br><font color="#FF5555"><b>Avoid contamination from plasticizers</b></font>
			<br>
			<br>To avoid contamination from plasticizers, use all fresh solvents. Never use any plastic pipettes to transfer solvents from the original bottles,
			instead poor the solvent into a beaker. Repeated exposure of solvents to plastics will contaminate the stock solvents with plasticizers.
			Never use plastic pipettes when handling concentrated (&gt;2%) acids, use glass pipettes or Hamilton syringes (rinse the syringe with water after
			using it for concentrated acids to avoid corrosion of the metal needle).
			If you don't know whether your stock solvents already are contaminated, buy new solvents and make sure no one is contaminating them!
			Keep your solvents in glass bottles, preferably with Teflon lined lids. Never use bottle lids that have foil backed cardboard liners! 
			
			
			<br>
			<br><b>Method</b>
			<br>
			<br>
			<ol>
			<li>Make 0.2% PPS diluted in 50 mM Ammonium Bicarbonate pH 7.8 (1 mg surfactant per 500 &#956;l 50 mM Ammonium Bicarbonate pH 7.8).
			<li>Using low adhesion microcentrifuge tubes, add 100 &#956;l 0.2% PPS per 100 &#956;l protein mixture (1:1) [final concentration of PPS should be 0.1% (w/v)]. If protein is in pellet, add 25-50 &#956;l of 0.1% PPS.
			<li>Vortex the sample.
			<li>Add DTT to a final concentration of 5mM.
			<li>Incubate sample at 50<sup>o</sup>C for 30 minutes.
			<li>Cool the sample to room temperature.
			<li>Add IAA to a final concentration of 15mM.
            <li>Place sample in dark at room temperature for 30 minutes.
            <li>Add CaCl<sub>2</sub> to a final concentration of 1mM.
            <li>Add trypsin for a final concentration of 1:50 enzyme:protein.
                <br>If total amount of protein is very low just add 1-2 &#956;g of trypsin.
			<li>Incubate 4h with shaking at 37<sup>o</sup>C.
			<li>Prior to mass spectrometry run, add HCl to a final concentration of 250 mM.
			<li>Allow the cleavage reaction to proceed for one hour at room temperature.
			<li>Spin sample and separate supernatant from the pellet into a fresh Eppendorf tube if necessary (e.g. approximately  16,000 x g, for 10 minutes).
			<li>Proceed with LC-MS analysis of the supernatant.
			
			</ol>
			
		 
