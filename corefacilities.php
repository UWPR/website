			which include Mass Spectrometry, NMR and Metabolic Imaging, Biostatistics &amp; Bioinformatics, and Promotional &amp; Outreach.  

			<br><a href="https://northwestmetabolomicsorg.wpcomstaging.com/">NORTHWEST METABOLOMICS RESEARCH CENTER</a></li>
			
			<li><p>The <b>Quantitative and Functional Proteomics Core</b>, is located at the University of Washington School of Medicine, South Lake Union (SLU). 
