			unknown sample analysis to quantitative assays. We provide hands-on training and enable walk-on usage of most of the 
			instruments providing education in multitude of aspects of mass spectrometry.  

			<br><a href="https://depts.washington.edu/chem/facilserv/massspec/">https://depts.washington.edu/chem/facilserv/massspec/</a></li>

